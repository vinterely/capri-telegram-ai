async def handle(event, status, question: str, client) -> bool:
    """نقطه‌ی ورود حالت رول‌پلی. True یعنی پیام کاملاً مدیریت شد و نیازی به ادامه‌ی ایجنت نیست."""
    intent, genre = _detect(question)

    if intent == "finish":
        await _finish(event, status, client)
        return True
    if intent == "pause":
        await _pause(event, status, client)
        return True
    if intent == "ask_genre":
        await _edit(status, "🎲 چه دنیایی می‌خوای؟ مثلاً بگو:\n«کاپری رول پلی قرون وسطا»\n«کاپری رول پلی دنیای مدرن»\n«کاپری رول پلی آینده‌ی سایبرپانک»")
        return True
    if intent == "resume":
        await _resume(event, status, client)
        return True
    if intent == "start":
        await _start(event, status, genre, client)
        return True

    if is_active():
        await _turn(event, status, question, client)
        return True

    return False
