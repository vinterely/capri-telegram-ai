def _norm(s: str) -> str:
    if not s:
        return ""
    t = s
    for a, b in (("ي", "ی"), ("ك", "ک"), ("\u200c", " "), ("\u200f", " "), ("\u200e", " "), ("‌", " ")):
        t = t.replace(a, b)
    return re.sub(r"\s+", " ", t).strip()


_RP_MARKS = ("رول پلی", "رولپلی", "نقش بازی", "نقشبازی", "رول پلی بازی")
_FINISH_WORDS = ("تموم", "تمام", "پایان", "خاتمه")
_PAUSE_WORDS = ("نگه دار", "نگهدار", "ذخیره", "برای بعدا", "برای بعد", "نگهش دار", "نگه دارش")
_RESUME_WORDS = ("ادامه بده", "ادامه کن", "ادامش بده", "ادامه", "شروع کن", "شروع")


def _find_mark(q: str):
    for m in _RP_MARKS:
        if q == m or q.startswith(m + " ") or q.startswith(m):
            return m, q.replace(m, " ", 1).strip()
    return None, None


def _parse_count(text: str) -> int:
    t = _norm(text)
    t = re.sub(r"[«»\"'،,:.؟?()\-_/]", " ", t)
    t = " ".join(t.split())
    mapping = {
        "2": 2, "3": 3, "4": 4, "۲": 2, "۳": 3, "۴": 4,
        "دو": 2, "سه": 3, "چهار": 4, "۲تا": 2, "۳تا": 3, "۴تا": 4,
        "2تا": 2, "3تا": 3, "4تا": 4, "دوتا": 2, "سه تا": 3, "چهارتا": 4,
        "دو تا": 2, "چهار تا": 4, "2 تا": 2, "3 تا": 3, "4 تا": 4,
    }
    if t in mapping:
        return mapping[t]
    m = re.match(r"^([0-9۰-۹]+)\s*$", t)
    if m:
        try:
            digits = m.group(1).translate(str.maketrans("۰۱۲۳۴۵۶۷۸۹", "0123456789"))
            n = int(digits)
            if 1 <= n <= 8:
                return n
        except Exception:
            pass
    return 0


def _detect(question: str):
    q = _norm(question)
    if not q:
        return "", None
    mark, rest = _find_mark(q)
    if mark is None:
        return "", None
    if any(w in rest for w in _FINISH_WORDS):
        return "finish", None
    if any(w in rest for w in _PAUSE_WORDS):
        return "pause", None
    rest_norm = re.sub(r"[«»\"'،,:.؟?()\-_/]", " ", rest).strip()
    rest_norm = " ".join(rest_norm.split())
    if rest_norm in _RESUME_WORDS:
        return "resume", None
    if not rest_norm:
        if has_saved():
            return "resume", None
        return "ask_genre", None
    return "start", rest


async def _call(prompt: str) -> str:
    """جمینای برای خروجی ساختاریافته‌ی مطمئن؛ در نبود آن، مدل فعال به‌عنوان پشتیبان."""
    raw = await asyncio.to_thread(ai._gemini, prompt)
    if not raw:
        raw = await asyncio.to_thread(ai.ask_direct, prompt, "")
    return (raw or "").strip()


def _extract_block(text: str, tag: str) -> str:
    """استخراج محتوای بین [TAG] و [/TAG] (خط مستقل). در نبود بلوک، رشته‌ی خالی."""
    start = f"[{tag}]"
    end = f"[/{tag}]"
    m = re.search(re.escape(start) + r"\s*\n(.*?)" + re.escape(end), text, re.DOTALL)
    if m:
        return m.group(1).strip()
    m2 = re.search(re.escape(start) + r"(.*?)" + re.escape(end), text, re.DOTALL)
    if m2:
        return m2.group(1).strip()
    return ""


async def _send(client, chat_id, text: str) -> None:
    """ارسال چندبخشی امن (تلگرام سقف ۴۰۹۶ کاراکتر دارد)."""
    text = (text or "").strip()
    if not text or client is None:
        return
    for chunk in _chunk(text, 3900):
        try:
            await client.send_message(chat_id, chunk)
        except Exception:
            pass


def _chunk(text: str, max_size: int):
    if len(text) <= max_size:
        return [text]
    parts = []
    buf = ""
    for line in text.split("\n"):
        if len(buf) + len(line) + 1 > max_size and buf:
            parts.append(buf)
            buf = ""
        buf = (buf + "\n" + line).strip("\n")
    if buf:
        parts.append(buf)
    return parts


def _history_text(d: dict) -> str:
    hist = d.get("history", [])
    if not hist:
        return ""
    lines = []
    for h in hist[-MAX_HISTORY:]:
        if h.get("user"):
            lines.append(f"کاربر: {h['user']}")
        if h.get("narrator"):
            lines.append(f"راوی: {h['narrator']}")
    return "\n".join(lines)


def _push_history(d: dict, user: str, narrator: str) -> None:
    hist = d.get("history", [])
    hist.append({"user": user[:1500], "narrator": narrator[:1500]})
    d["history"] = hist[-MAX_HISTORY:]


