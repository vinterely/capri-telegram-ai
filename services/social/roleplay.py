    await _edit(status, "📖 راوی در حال نوشتن...")
    d = load()
    state = d.get("state", "")
    phase = d.get("phase", "playing")
    count = _parse_count(question)
    if phase == "intro" and count:
        await _characters(event, status, count, client)
        return

    hist = _history_text(d)
    prompt = (
        RP_SYSTEM + "\n\n"
        "=== وضعیت فعلی داستان (حافظه‌ی رول‌پلی) ===\n" + (state or "—") + "\n\n"
    )
    if hist:
        prompt += "=== گفتگوی اخیر ===\n" + hist + "\n\n"
    prompt += (
        "=== اقدام/پیام کاربر ===\n" + question + "\n\n"
        "دستور: طبق وضعیت ثبت‌شده، به‌عنوان راوی واکنش جهان و پیشرفت داستان را روایت کن. "
        "اگر کاربر پرسشی درباره‌ی موجودی/وضعیت خودش دارد، از وضعیت ثبت‌شده استخراج کن. "
        "تصمیم‌های مهم شخصیت کاربر را به‌جای او نگیر؛ پیامدها، منابع و آسیب‌ها را اعمال کن. "
        "در پایان، وضعیت داستان را به‌روز کن.\n\n"
        "خروجی دقیقاً در این قالب (فارسی):\n"
        "[روایت]\n"
        "<متن داستان/پاسخ راوی>\n"
        "[/روایت]\n"
        "[وضعیت]\n"
        "<وضعیت به‌روزشده در ۹ بخش>\n"
        "[/وضعیت]\n"
    )
    raw = await _call(prompt)
    narration = _extract_block(raw, "روایت")
    new_state = _extract_block(raw, "وضعیت")
    if not narration:
        narration = raw
    if new_state:
        d["state"] = new_state.strip()
    d["updated"] = time.time()
    _push_history(d, question, narration.strip())
    save(d)
    await _send(client, event.chat_id, narration)


